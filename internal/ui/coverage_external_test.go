// TestCoverageViewCycle pins the mode cycle cone -> shadows -> off -> cone
// and the cone default.
func TestCoverageViewCycle(t *testing.T) {
	t.Parallel()

	view := ui.NewCoverageView()
	if got := view.Mode(); got != ui.CoverageCone {
		t.Fatalf("new view mode = %v, want cone", got)
	}

	for _, want := range []ui.CoverageMode{ui.CoverageShadows, ui.CoverageOff, ui.CoverageCone} {
		view.Cycle()

		if got := view.Mode(); got != want {
			t.Errorf("after Cycle mode = %v, want %v", got, want)
		}
	}
}

// TestCoverageModeString pins the footer-chip label for every mode plus the
// out-of-range fallback.
func TestCoverageModeString(t *testing.T) {
	t.Parallel()

	for _, testCase := range []struct {
		name string
		mode ui.CoverageMode
		want string
	}{
		{"cone", ui.CoverageCone, "cone"},
		{"shadows", ui.CoverageShadows, "shadows"},
		{"off", ui.CoverageOff, "off"},
		{"unknown", ui.CoverageMode(9), "?"},
	} {
		t.Run(testCase.name, func(t *testing.T) {
			t.Parallel()

			if got := testCase.mode.String(); got != testCase.want {
				t.Errorf("String() = %q, want %q", got, testCase.want)
			}
		})
	}
}

// TestUpdateCoveragePanelPerMode confirms the side-effecting panel setter
// dispatches to the right formatter for each mode and clears the panel when
// off.
func TestUpdateCoveragePanelPerMode(t *testing.T) {
	t.Parallel()

	for _, testCase := range []struct {
		name string
		mode ui.CoverageMode
		want string
	}{
		{"cone renders the caption", ui.CoverageCone, "max — nm"},
		{"shadows renders the placeholder", ui.CoverageShadows, "no coverage yet"},
		{"off clears the panel", ui.CoverageOff, ""},
	} {
		t.Run(testCase.name, func(t *testing.T) {
			t.Parallel()

			panel := tview.NewTextView()
			ui.UpdateCoveragePanel(panel, testCase.mode, coverage.Snapshot{})

			got := panel.GetText(true)
			if testCase.want == "" {
				if got != "" {
					t.Errorf("panel text = %q, want empty", got)
				}

				return
			}

			if !strings.Contains(got, testCase.want) {
				t.Errorf("panel text = %q, want substring %q", got, testCase.want)
			}
		})
	}
}
