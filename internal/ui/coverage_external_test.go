const (
	coveragePanelWidth  = 46
	coveragePanelHeight = 12

	// Seeded-fixture parameters. seededCountStep scales the per-cell count
	// so the seeded cone sweeps through every density glyph; the two range
	// values drive the caption.
	seededCountStep     = 9
	seededMaxRangeNm    = 152
	seededMaxRangeAltFt = 38000
)

// seededCoverageCone builds a deterministic cone whose reception reach
// widens with altitude (high aircraft are seen farther) and whose counts
// fall with range, so the rendered glyphs sweep from full blocks near the
// receiver to empty-cell dots at the edges. It is the exact input the
// golden fixture was generated from — regenerate the fixture by feeding
// this snapshot back through FormatCoverageCone.
func seededCoverageCone() coverage.Snapshot {
	var snap coverage.Snapshot

	reach := [coverage.AltitudeBandCount]int{2, 4, 7, 10, 13, 16, 19, 22, 24, 25}
	for band := range coverage.AltitudeBandCount {
		for bin := range reach[band] {
			//nolint:gosec // (reach-bin)*step is a small positive product; no uint32 overflow.
			snap.Cells[band][bin] = uint32((reach[band] - bin) * seededCountStep)
		}
	}

	snap.MaxRangeNm = seededMaxRangeNm
	snap.MaxRangeAltFt = seededMaxRangeAltFt

	return snap
}

// seededCoverageShadows builds a silhouette with a hard null: bearing
// sectors 6 and 7 (the SE quadrant) carry zero range, so the plot renders
// a missing wedge — the antenna shadow the view is meant to surface.
func seededCoverageShadows() coverage.Snapshot {
	var snap coverage.Snapshot

	snap.Sectors = [coverage.BearingSectorCount]float64{
		140, 150, 120, 100, 80, 60, 0, 0, 90, 110, 130, 120, 100, 70, 60, 90,
	}
	snap.MaxRangeNm = seededMaxRangeNm
	snap.MaxRangeAltFt = seededMaxRangeAltFt

	return snap
}

// readGolden loads a byte-exact fixture from testdata. Fixtures are
// regenerated by writing the corresponding Format* output back to the file.
func readGolden(t *testing.T, name string) string {
	t.Helper()

	//nolint:gosec // test-only golden fixture; name is a compile-time literal from this file.
	body, err := os.ReadFile(filepath.Join("testdata", name))
	if err != nil {
		t.Fatalf("read golden %s: %v", name, err)
	}

	return string(body)
}

// TestFormatCoverageConeEmpty pins the empty-tracker cone: every cell is
// the empty glyph, the four altitude labels sit on their rows, the ruler
// anchors 0/100/200 nm, and the caption shows the no-data dash.
func TestFormatCoverageConeEmpty(t *testing.T) {
	t.Parallel()

	got := ui.FormatCoverageCone(coverage.Snapshot{}, coveragePanelWidth, coveragePanelHeight)
	if want := readGolden(t, "coverage_cone_empty.golden"); got != want {
		t.Errorf("cone (empty) mismatch\ngot:\n%s\n\nwant:\n%s", got, want)
	}
}

// TestFormatCoverageConeSeeded pins the seeded cone: the density glyphs
