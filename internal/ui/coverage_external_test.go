// TestFormatCoverageConeTinyPanel drives the clamp paths: a width below the
// label gutter yields zero distance columns, and a height below the row
// count truncates to the top altitude bands.
func TestFormatCoverageConeTinyPanel(t *testing.T) {
	t.Parallel()

	const (
		tinyWidth  = 2
		tinyHeight = 4
	)

	got := ui.FormatCoverageCone(seededCoverageCone(), tinyWidth, tinyHeight)
	if want := "    \n40k \n    \n30k "; got != want {
		t.Errorf("cone (tiny) = %q, want %q", got, want)
	}
}

